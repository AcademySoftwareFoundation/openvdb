TEST(Blosc, ReadBloscLZ)
{
    checkPayload(plain, 1024);
    checkPayload(shuffled, 1024);
    checkPayload(partial, 1027);
}

TEST(Blosc, RejectUnsupportedFormat)
{
    std::array<unsigned char, 1024> output;
    for (const unsigned char* input : {plain, shuffled}) {
        const size_t size = input == plain ? sizeof(plain) : sizeof(shuffled);
        std::vector<unsigned char> bad(input, input + size);
        bad[2] = (bad[2] & 0x1f) | (4 << 5); // Zstd is still unsupported.
        EXPECT_LT(nanovdb_blosc_decompress_ctx(bad.data(), output.data(), output.size(), 1), 0);
        bad.assign(input, input + size);
        bad[1] = 255; // Unsupported BloscLZ format version.
        EXPECT_LT(nanovdb_blosc_decompress_ctx(bad.data(), output.data(), output.size(), 1), 0);
    }
}

TEST(Blosc, RejectInvalidBloscLZBlock)
{
    // A valid Blosc envelope containing an incomplete BloscLZ literal.
    const unsigned char truncated[] = {
        2, 1, 0x10, 1, // Blosc v2, BloscLZ v1, no split, typesize 1.
        128, 0, 0, 0, // Uncompressed size.
        128, 0, 0, 0, // Block size.
        25, 0, 0, 0,  // Compressed size.
        20, 0, 0, 0,  // Block offset.
        1, 0, 0, 0,   // Compressed block length.
        0x3f          // Claims 32 literal bytes, but none follow.
    };
    std::array<unsigned char, 128> output;
    EXPECT_LT(nanovdb_blosc_decompress_ctx(truncated, output.data(), output.size(), 1), 0);

    // A literal followed by a match that refers before the output buffer.
    const unsigned char invalidMatch[] = {
        2, 1, 0x10, 1, 128, 0, 0, 0, 128, 0, 0, 0,
        29, 0, 0, 0, 20, 0, 0, 0, 5, 0, 0, 0,
        0x20, 'a', 0x20, 0xff, 0
    };
    EXPECT_LT(nanovdb_blosc_decompress_ctx(invalidMatch, output.data(), output.size(), 1), 0);
}

TEST(Blosc, KeepLZ4Writer)
{
    std::array<unsigned char, 1024> input;
    for (size_t i = 0; i < input.size(); ++i) input[i] = i % 32;
    std::array<unsigned char, 1040> compressed;
    const int count = nanovdb_blosc_compress_ctx(9, 1, 8, input.size(), input.data(),
        compressed.data(), compressed.size(), NANOVDB_BLOSC_LZ4_COMPNAME, 256, 1);
    ASSERT_GT(count, 0);
    ASSERT_EQ(1, compressed[2] >> 5); // The writer still chooses LZ4.
    checkPayload(compressed.data(), input.size());

    compressed[1] = 255;
    std::array<unsigned char, 1024> output;
    EXPECT_LT(nanovdb_blosc_decompress_ctx(compressed.data(), output.data(), output.size(), 1), 0);
}

TEST(Blosc, ReadUncompressedBloscLZBuffer)
{
    // Blosc may store incompressible data directly, even for a BloscLZ stream.
    std::array<unsigned char, 48> stored = {
        2, 1, 2, 1, 32, 0, 0, 0, 32, 0, 0, 0, 48, 0, 0, 0
    };
    for (size_t i = 0; i < 32; ++i) stored[16 + i] = static_cast<unsigned char>(i);
    checkPayload(stored.data(), 32);
    // Blosc memcpy buffers contain the original bytes; no filter is applied.
    stored[2] |= 0x04;
    checkPayload(stored.data(), 32);
}

TEST(Blosc, RejectBitShuffle)
{
    // Generated with c-blosc 1.21.6 from 128 bytes of i % 32:
    // blosc_compress_ctx(9, 2, 1, 128, input, output, 144, codec, 0, 1).
    // Both payloads use real bit-shuffle, not a modified byte-shuffle header.
    const unsigned char blosclz[] = {
        0x02, 0x01, 0x04, 0x01, 0x80, 0x00, 0x00, 0x00, 0x80, 0x00, 0x00, 0x00,
        0x3c, 0x00, 0x00, 0x00, 0x14, 0x00, 0x00, 0x00, 0x24, 0x00, 0x00, 0x00,
        0x23, 0xaa, 0xaa, 0xaa, 0xaa, 0xe0, 0x03, 0x03, 0x00, 0xcc, 0xe0, 0x06,
        0x00, 0x00, 0xf0, 0xe0, 0x06, 0x00, 0x01, 0x00, 0xff, 0xe0, 0x06, 0x01,
        0x01, 0x00, 0xff, 0xe0, 0x06, 0x03, 0xe0, 0x23, 0x00, 0x01, 0x00, 0x00,
    };
    const unsigned char lz4[] = {
        0x02, 0x01, 0x24, 0x01, 0x80, 0x00, 0x00, 0x00, 0x80, 0x00, 0x00, 0x00,
        0x38, 0x00, 0x00, 0x00, 0x14, 0x00, 0x00, 0x00, 0x20, 0x00, 0x00, 0x00,
        0x1b, 0xaa, 0x01, 0x00, 0x1b, 0xcc, 0x01, 0x00, 0x1b, 0xf0, 0x01, 0x00,
        0x2b, 0x00, 0xff, 0x02, 0x00, 0x2b, 0x00, 0xff, 0x04, 0x00, 0x0f, 0x02,
        0x00, 0x16, 0x50, 0x00, 0x00, 0x00, 0x00, 0x00,
    };

    for (const unsigned char* input : {blosclz, lz4}) {
        std::array<unsigned char, 128> output;
        output.fill(0xa5);
        const auto untouched = output;
        EXPECT_LT(nanovdb_blosc_decompress_ctx(input, output.data(), output.size(), 1), 0);
        EXPECT_EQ(untouched, output);
    }
}
