void checkPayload(const unsigned char* compressed, size_t bytes)
{
    std::vector<unsigned char> output(bytes + 2, 0xa5);
    ASSERT_EQ(int(bytes), nanovdb_blosc_decompress_ctx(compressed, output.data() + 1, bytes, 1));
    EXPECT_EQ(0xa5, output.front());
    EXPECT_EQ(0xa5, output.back());
    for (size_t i = 0; i < bytes; ++i) EXPECT_EQ(i % 32, output[i + 1]) << i;
    EXPECT_LT(nanovdb_blosc_decompress_ctx(compressed, output.data() + 1, bytes - 1, 1), 0);
}
